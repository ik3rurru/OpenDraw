use super::{Color, FrameBuffer, Rect};

impl FrameBuffer {
    pub fn draw_text(&mut self, x: i32, y: i32, text: &str, color: Color, scale: u32) {
        assert!(scale > 0);
        let advance = 6_i64 * scale as i64;

        for (index, character) in text.chars().enumerate() {
            let glyph = glyph(character);
            let glyph_x = x as i64 + index as i64 * advance;
            for (row, bits) in glyph.into_iter().enumerate() {
                for column in 0..5 {
                    if bits & (1 << (4 - column)) != 0 {
                        let pixel_x = glyph_x + column as i64 * scale as i64;
                        let pixel_y = y as i64 + row as i64 * scale as i64;
                        if let (Ok(pixel_x), Ok(pixel_y)) =
                            (i32::try_from(pixel_x), i32::try_from(pixel_y))
                        {
                            self.fill_rect(Rect::new(pixel_x, pixel_y, scale, scale), color);
                        }
                    }
                }
            }
        }
    }

    pub fn measure_text(text: &str, scale: u32) -> u32 {
        let characters = text.chars().count() as u32;
        characters
            .saturating_mul(6)
            .saturating_sub(u32::from(characters > 0))
            .saturating_mul(scale)
    }
}

